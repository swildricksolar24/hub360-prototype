// Builds tokens/tokens.json (W3C DTCG) and tokens/tokens.css from figma-export/variables.json.
// Usage: node design-system/scripts/build-tokens.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(join(root, 'figma-export', 'variables.json'), 'utf8'));

const PREFIX = { 'Spacing': 'space', 'Corner Radius': 'radius', 'Strokes': 'stroke-width', 'Colors': 'color', 'Typography': '' };
const slug = s => s.toLowerCase().replace(/\s*-\s*/g, '-').replace(/\s+/g, '-');
const pathOf = (collection, name) => [PREFIX[collection], ...name.split('/').map(slug)].filter(Boolean);

// "Collection::Variable name" -> token path. Names like "8" repeat across Spacing/Radius/Strokes, so the key includes the collection.
const index = {};
for (const c of src.collections) for (const [name] of c.variables) index[`${c.name}::${name}`] = pathOf(c.name, name);
// Figma aliases in this file always point within the same collection
const target = (collection, name) => index[`${collection}::${name}`];

const cssVar = path => `--${path.join('-')}`;
const isAlias = v => typeof v === 'string' && /^\{.+\}$/.test(v);

function toCss(collection, name, v) {
  if (isAlias(v)) return `var(${cssVar(target(collection, v.slice(1, -1)))})`;
  if (v && typeof v === 'object' && v.alias) return `color-mix(in srgb, var(${cssVar(target(collection, v.alias))}) ${Math.round(v.opacity * 100)}%, transparent)`;
  if (typeof v === 'number') return collection === 'Typography' && name.startsWith('Font Family') ? v : `${v}px`;
  if (collection === 'Typography' && name.startsWith('Font Family')) return `"${v}", system-ui, sans-serif`;
  return v;
}

function toDtcg(collection, v) {
  if (isAlias(v)) return `{${target(collection, v.slice(1, -1)).join('.')}}`;
  if (v && typeof v === 'object' && v.alias) return { color: `{${target(collection, v.alias).join('.')}}`, alpha: v.opacity };
  if (typeof v === 'number') return `${v}px`;
  return v;
}

const DTCG_TYPE = { COLOR: 'color', FLOAT: 'dimension', STRING: 'fontFamily' };

// ---- DTCG JSON ----
const dtcg = { $description: `Imported from ${src.source} on ${src.exported}. $value is the first Figma mode; other modes are under $extensions["com.figma"].modes.` };
for (const c of src.collections) {
  for (const [name, type, scopes, ...values] of c.variables) {
    const path = target(c.name, name);
    let node = dtcg;
    for (const seg of path.slice(0, -1)) node = node[seg] ??= {};
    const token = { $type: DTCG_TYPE[type], $value: toDtcg(c.name, values[0]) };
    const ext = { collection: c.name, figmaName: name, scopes };
    if (values.length > 1) ext.modes = Object.fromEntries(c.modes.map((m, i) => [m, toDtcg(c.name, values[i])]));
    token.$extensions = { 'com.figma': ext };
    node[path.at(-1)] = token;
  }
}
const WEIGHT = { 'Regular': 400, 'Medium': 500, 'Semi Bold': 600, 'Bold': 700 };
dtcg.typography = {};
for (const [name, family, style, size, lh] of src.textStyles) {
  const [group, variant] = name.split('/').map(slug);
  (dtcg.typography[group] ??= {})[variant] = {
    $type: 'typography',
    $value: { fontFamily: family, fontWeight: WEIGHT[style], fontSize: `${size}px`, lineHeight: lh === 'auto' ? 'normal' : `${lh}px`, letterSpacing: '0px' }
  };
}
dtcg.shadow = { drop: { $type: 'shadow', $value: { color: '#00000040', offsetX: '0px', offsetY: '4px', blur: '4px', spread: '0px' } } };

// ---- CSS ----
const lines = { root: [], dark: [], mobile: [] };
for (const c of src.collections) {
  lines.root.push(`  /* ${c.name} */`);
  for (const [name, , , ...values] of c.variables) {
    const v = cssVar(target(c.name, name));
    lines.root.push(`  ${v}: ${toCss(c.name, name, values[0])};`);
    if (values.length > 1 && JSON.stringify(values[1]) !== JSON.stringify(values[0])) {
      const modeLines = c.name === 'Typography' ? lines.mobile : lines.dark;
      modeLines.push(`  ${v}: ${toCss(c.name, name, values[1])};`);
    }
  }
}
lines.root.push('  /* Effects */', '  --shadow-drop: 0 4px 4px 0 #00000040;');

const classes = src.textStyles
  .filter(([name]) => !name.startsWith('Annotation'))
  .map(([name, family, style, size, lh, bound]) => {
    const [group] = name.split('/');
    const g = slug(group);
    const tokenized = bound && target('Typography', `Font Size/${group}`);
    const fs = tokenized ? `var(--font-size-${g})` : `${size}px`;
    const lhv = tokenized ? `var(--line-height-${g})` : `${lh}px`;
    return `.text-${name.split('/').map(slug).join('-')} { font-family: var(--font-family-inter); font-weight: ${WEIGHT[style]}; font-size: ${fs}; line-height: ${lhv}; }`;
  });

const css = `/* Generated by design-system/scripts/build-tokens.mjs from figma-export/variables.json. Do not edit by hand.
 * Source: ${src.source}
 * Theme: set data-theme="dark" | "light" on <html>. Semantic tokens reference primitives through var(),
 * so the attribute must be on the same element as :root for dark values to resolve. */

:root {
${lines.root.join('\n')}
}

:root[data-theme="dark"] {
${lines.dark.join('\n')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${lines.dark.map(l => '  ' + l).join('\n')}
  }
}

/* Typography: Mobile mode */
@media (max-width: 767px) {
  :root {
${lines.mobile.map(l => '  ' + l).join('\n')}
  }
}

/* Text styles */
${classes.join('\n')}
`;

mkdirSync(join(root, 'tokens'), { recursive: true });
writeFileSync(join(root, 'tokens', 'tokens.json'), JSON.stringify(dtcg, null, 2) + '\n');
writeFileSync(join(root, 'tokens', 'tokens.css'), css);
const count = src.collections.reduce((n, c) => n + c.variables.length, 0);
console.log(`Wrote ${count} variables + ${src.textStyles.length} text styles -> tokens/tokens.json, tokens/tokens.css`);
